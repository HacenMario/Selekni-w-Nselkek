#!/usr/bin/env python3
"""Cost + valuation model for 'SeleKni w NselKek' — based on the actual
component inventory of the app as built (13 versions), hours estimated per
component, priced at four market rate scenarios. All numbers printed."""

components = [
    ("تحليل وتصميم واجهات (PWA موبايل، 9 لغات، RTL)", 40),
    ("الحسابات والأمان (بريد+جوال، Google OAuth، JWT، تحقق بالبطاقة، أدوار)", 55),
    ("نظام العروض (CRUD، صور، 18 تصنيفاً بـ9 لغات، حالات حية، بحث)", 55),
    ("خط الفيديو (رفع مجزأ، GridFS، بث Range، سقف 30MB، تنظيف اليتائم)", 45),
    ("الاشتراكات وبوابة النشر", 30),
    ("الإشعارات (Web Push/VAPID، SW، محتوى بلغة المستخدم، تنبيه صوتي)", 35),
    ("التعدد اللغوي (9 لغات × 477 مفتاحاً، أعلام SVG، RTL كامل)", 40),
    ("الهوية البصرية (10 باليتات، وضع ليلي، تكبير الخط، طلاء مبكر)", 20),
    ("لوحة الإدارة (إحصاء، مستخدمون، عروض، شكاوى، بث، إعدادات)", 55),
    ("PWA (manifest، أيقونات، SW بكاش مُدار، قشرة offline)", 20),
    ("النشر والتشغيل (Vercel+Railway+MongoDB، متغيرات، CORS، OAuth)", 25),
    ("الاختبارات (انحدار API ×9 إصدارات، فيديو e2e 26 فحصاً، متصفح حقيقي)", 45),
    ("تلميع وتصحيح عبر 13 إصداراً", 55),
    ("صفحات قانونية/تواصل/شكاوى + توثيق", 20),
]

total_h = sum(h for _, h in components)
print(f"إجمالي الساعات المقدرة: {total_h} ساعة\n")

scenarios = [
    ("مستقل جزائري/شمال أفريقي", 12),
    ("مستقل محترف عن بُعد (متوسط Upwork)", 35),
    ("وكالة/استوديو تطوير (متوسط عالمي $30-49 + هامش)", 60),
    ("وكالة/فريق في أمريكا وأوروبا", 110),
]
print(f"{'السيناريو':45s} {'$/س':>5s} {'التكلفة':>12s}")
for name, rate in scenarios:
    print(f"{name:45s} {rate:5d} {total_h*rate:12,} $")

print("\n— جدول تفصيلي بسعر المستقل المحترف ($35/س) —")
for name, h in components:
    print(f"{name:60s} {h:3d} ساعة  {h*35:6,} $")

print("\n=== التقييم عند البيع ===")
mid_cost = total_h * 35
print(f"كلفة إعادة الإنتاج (متوسط محترف): {mid_cost:,} $")
print("\nأ) بلا مستخدمين ولا إيراد (قيمة أصول الكود والتصميم = 15-25% من كلفة إعادة الإنتاج):")
print(f"   {int(mid_cost*0.15):,} $ — {int(mid_cost*0.25):,} $")
print("\nب) مع جمهور نشط بلا إيراد (قيمة الجمهور فوق الأصول):")
for mau, prem in [(500, 1500), (2000, 4000), (5000, 9000)]:
    print(f"   ~{mau:,} مستخدم نشط: {int(mid_cost*0.15)+prem:,} — {int(mid_cost*0.25)+prem:,} $")
print("\nج) مع إيراد صافٍ شهري (مضاعف السوق المعتاد للتطبيقات الصغيرة 24-48× الشهري = 2-4× السنوي):")
for p in [100, 300, 500, 1000, 2000]:
    print(f"   {p:5,} $/شهر  →  {p*24:7,} — {p*48:7,} $")
print("\nملاحظة: الأرقام تقديرات مبنية على الجرد الفعلي للكود + أسعار السوق المنشورة، وليست عرضاً ملزماً.")
