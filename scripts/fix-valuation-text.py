#!/usr/bin/env python3
"""Text fixes for the valuation report generator:
- duplicated word typo, dash-based numeric ranges (bidi scrambles them in RTL)
  -> 'من/إلى' wording, and × signs in table headers/captions -> 'ضعفاً'."""
import io

p = "/home/z/my-project/scripts/gen-valuation-docx.js"
s = io.open(p, encoding="utf-8").read()

pairs = [
    ("والعروض المحلية المحلية بقليل", "والعروض المحلية بقليل"),
    ("تصل 150–200 دولار", "تصل من 150 إلى 200 دولار"),
    ("(9 لغات × 477 مفتاحاً، أعلام رسمية، RTL كامل)", "(9 لغات و477 مفتاحاً، أعلام رسمية، RTL كامل)"),
    ("تساوي 15–25% من كلفة", "تساوي من 15% إلى 25% من كلفة"),
    ('b("4,300 – 6,200 دولار")', 'b("من 4,300 إلى 6,200 دولار")'),
    ('b("6,800 – 8,700 دولار")', 'b("من 6,800 إلى 8,700 دولار")'),
    ('b("11,800 – 13,700 دولار")', 'b("من 11,800 إلى 13,700 دولار")'),
    ("(مضاعف 24–48×)", "(مضاعف 24 إلى 48 ضعفاً)"),
    ('"السعر عند 24×"', '"السعر عند 24 ضعفاً"'),
    ('"السعر عند 48×"', '"السعر عند 48 ضعفاً"'),
    ("المضاعف الأعلى (48×) يتحقق", "المضاعف الأعلى (48 ضعفاً) يتحقق"),
    ("لجمع 1,000–2,000 مستخدم نشط", "لجمع 1,000 إلى 2,000 مستخدم نشط"),
    ("حالة الأصول (2,800–4,700 دولار)", "حالة الأصول (2,800 إلى 4,700 دولار)"),
    ("يساوي عملياً 12,000–24,000 دولار", "يساوي عملياً من 12,000 إلى 24,000 دولار"),
    ("أكبر شريحة 30–49 دولاراً للساعة", "أكبر شريحة من 30 إلى 49 دولاراً للساعة"),
    ("نطاق 5,000–50,000 دولار للمشاريع الصغيرة", "نطاق من 5,000 إلى 50,000 دولار للمشاريع الصغيرة"),
    ("(30–60 دولاراً للساعة)", "(من 30 إلى 60 دولاراً للساعة)"),
]
for old, new in pairs:
    assert s.count(old) == 1, f"{s.count(old)} matches for: {old[:50]}"
    s = s.replace(old, new)
io.open(p, "w", encoding="utf-8").write(s)
print("OK", len(pairs), "replacements applied")
