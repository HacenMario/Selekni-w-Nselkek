#!/usr/bin/env python3
"""Generate public/sw-i18n.js from src/lib/i18n.ts — the service worker imports it
so background phone notifications carry FULL details in the reader's language."""
import re

SRC = 'src/lib/i18n.ts'
OUT = 'public/sw-i18n.js'

# notification type -> (title key, body key) in i18n.ts
TYPES = {
    'new_offer_match': ('notifNewOffer', 'notifNewOfferBody'),
    'offer_accepted': ('notifOfferAccepted', 'notifOfferAcceptedBody'),
    'offer_awaiting': ('notifOfferAwaiting', 'notifOfferAwaitingBody'),
    'offer_done': ('notifOfferDone', 'notifOfferDoneBody'),
    'offer_cancelled': ('notifOfferCancelled', 'notifOfferCancelledBody'),
    'dues_reminder': ('notifDuesReminder', 'notifDuesReminderBody'),
    'dues_paid': ('notifDuesPaid', 'notifDuesPaidBody'),
    'dues_proof_submitted': ('notifDuesProofSubmitted', 'notifDuesProofSubmittedBody'),
    'dues_proof_approved': ('notifDuesProofApproved', 'notifDuesProofApprovedBody'),
    'dues_proof_rejected': ('notifDuesProofRejected', 'notifDuesProofRejectedBody'),
    'id_pending': ('notifAdminIdNew', 'notifAdminIdNew'),
    'complaint_new': ('notifComplaintNew', 'notifComplaintNewBody'),
    'complaint_resolved': ('notifComplaintResolved', 'notifComplaintResolvedBody'),
}

LANGS = ['ar', 'fr', 'en', 'tr', 'es', 'it', 'de', 'ru', 'zh']

def unescape(v: str) -> str:
    return v.replace("\\'", "'")

src = open(SRC, encoding='utf-8').read()

def extract(lang: str) -> dict:
    start = src.index(f'const {lang}: Dict = {{')
    end = src.index('\n};\n', start)
    block = src[start:end]
    out = {}
    for m in re.finditer(r"^  ([A-Za-z0-9_]+): '((?:\\.|[^'\\])*)',?\s*$", block, re.M):
        out[m.group(1)] = unescape(m.group(2))
    return out

lines = ['/* AUTO-GENERATED by scripts/gen-sw-i18n.py — do not edit by hand.',
         '   Phone-notification texts for all 9 interface languages (v4.16). */',
         'self.SW_NOTIF = {']
for lang in LANGS:
    d = extract(lang)
    lines.append(f'  {lang}: {{')
    for typ, (tk, bk) in TYPES.items():
        t = d.get(tk)
        b = d.get(bk)
        assert t and b, f'{lang}: missing {tk}/{bk}'
        tj = t.replace('\\', '\\\\').replace("'", "\\'")
        bj = b.replace('\\', '\\\\').replace("'", "\\'")
        lines.append(f"    {typ}: {{ t: '{tj}', b: '{bj}' }},")
    lines.append('  },')
lines.append('};')
lines.append('')
open(OUT, 'w', encoding='utf-8').write('\n'.join(lines))
print(f'sw-i18n.js written: {len(LANGS)} languages x {len(TYPES)} types')
