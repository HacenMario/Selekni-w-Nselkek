s = io.open(PATH, encoding="utf-8").read()
occ = [m.start() for m in re.finditer(r"^  subscriptionTitle: ", s, flags=re.M)]
print("anchors found:", len(occ))
assert len(occ) == 9, "expected exactly 9 subscriptionTitle anchors"

# build insertion blocks per language (insert AFTER each anchor line)
lines = s.split("\n")
insert_at = []  # (line_index_after_which_to_insert, lang)
for i, ln in enumerate(lines):
    if ln.startswith("  subscriptionTitle: "):
        insert_at.append(i)
assert len(insert_at) == 9

def js(v: str) -> str:
    return "'" + v.replace("\\", "\\\\").replace("'", "\\'") + "'"

# insert from the last anchor backwards to keep indices valid
total_added = 0
for idx in reversed(range(9)):
    lang = ORDER[idx]
    block = [f"  // v4.14 — commission dues (replaces subscriptions)"] + [f"  {k}: {js(v)}," for k, v in KEYS[lang].items()]
    lines[insert_at[idx] + 1:insert_at[idx] + 1] = block
    total_added += len(block)

io.open(PATH, "w", encoding="utf-8").write("\n".join(lines))
print("inserted lines:", total_added)

# verify: every key appears exactly 9 times
out = io.open(PATH, encoding="utf-8").read()
bad = []
for lang in ORDER:
    for k in KEYS[lang]:
        n = len(re.findall(rf"^\s*{k}: ", out, flags=re.M))
        if n != 9:
            bad.append((lang, k, n))
