export const dictionaries: Record<Lang, Dict> = { ar, fr, en, tr, es, it, de, ru, zh };

export function translate(lang: Lang, key: string, params?: Record<string, string | number>): string {
  let s = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  }
  return s;
}

export function categoryLabel(cat: { key: string; label: { ar: string; fr: string; en: string; tr?: string; es?: string; it?: string; de?: string; ru?: string; zh?: string } }, lang: Lang): string {
  return cat.label[lang] || cat.label.en || cat.label.fr || cat.label.ar;
}
